import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { chmod, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { inspectFolder } from "./detection";
import { DesktopLibrary } from "./library";
import { runtimeExecutable } from "./runtimes";
import { changePlugins, listPlugins, parsePlugins } from "./plugins";
import { digest, exists, LibraryStore, ownedPath } from "./storage";

let directory: string;
let gameFolder: string;
let root: string;
let store: LibraryStore;
let library: DesktopLibrary;
const original =
  '// Generated by RPG Maker.\nvar $plugins =\n[{"name":"Lighting","status":true,"description":"Lighting effects","parameters":{"intensity":"2"},"custom":"keep"},{"name":"Weather","status":false,"description":"","parameters":{}}];\n';

beforeEach(async () => {
  directory = await mkdtemp(path.join(tmpdir(), "aperto-test-"));
  gameFolder = path.join(directory, "The Quiet Valley");
  root = path.join(gameFolder, "www");
  await mkdir(path.join(root, "js", "plugins"), { recursive: true });
  await mkdir(path.join(root, "data"));
  await writeFile(
    path.join(root, "package.json"),
    JSON.stringify({ name: "game", main: "index.html", window: { title: "Game" } }),
  );
  await writeFile(path.join(root, "index.html"), "<!doctype html><title>Fixture</title>");
  await writeFile(path.join(root, "js", "rpg_core.js"), "// MV fixture");
  await writeFile(path.join(root, "js", "plugins.js"), original);
  await writeFile(path.join(root, "js", "plugins", "Lighting.js"), "// plugin fixture");
  await writeFile(path.join(root, "js", "plugins", "Weather.js"), "// plugin fixture");
  store = new LibraryStore(path.join(directory, "data"));
  await store.load();
  library = new DesktopLibrary(
    store,
    {
      chooseFolder: async () => gameFolder,
      chooseArtwork: async () => null,
      image: async () => null,
      reveal: () => {},
    },
    () => {},
  );
});
afterEach(async () => {
  await rm(directory, { recursive: true, force: true });
});

async function importGame() {
  const review = (await library.handle({ action: "chooseImport" })) as Awaited<
    ReturnType<typeof inspectFolder>
  >;
  const candidate = review.candidates[0]!;
  await library.handle({
    action: "import",
    token: candidate.token,
    name: candidate.name,
    tags: "Adventure, adventure",
  });
  return store.value.games[0]!;
}

describe("import and persistence", () => {
  it("finds an internal www application, skips generic metadata, and prefers a real game title", async () => {
    expect((await inspectFolder(gameFolder)).candidates[0]?.name).toBe("The Quiet Valley");
    await writeFile(
      path.join(root, "data", "System.json"),
      JSON.stringify({ gameTitle: "Valley at Night" }),
    );
    expect((await inspectFolder(gameFolder)).candidates[0]?.name).toBe("Valley at Night");
    await writeFile(path.join(root, "data", "System.json"), "invalid");
    await writeFile(
      path.join(root, "package.json"),
      JSON.stringify({
        name: "game",
        main: "index.html",
        window: { title: "The Game of Seasons" },
      }),
    );
    expect((await inspectFolder(gameFolder)).candidates[0]?.name).toBe("The Game of Seasons");
  });
  it("reports ambiguous applications and rejects escaping entries", async () => {
    await writeFile(
      path.join(gameFolder, "package.json"),
      JSON.stringify({ name: "another-game", main: "www/index.html" }),
    );
    expect((await inspectFolder(gameFolder)).candidates).toHaveLength(2);
    await writeFile(
      path.join(root, "package.json"),
      JSON.stringify({ name: "game", main: "../../outside.html" }),
    );
    await writeFile(path.join(directory, "outside.html"), "outside");
    const review = await inspectFolder(gameFolder);
    expect(review.problems.join(" ")).toContain("outside its folder");
  });
  it("persists records, prevents duplicate imports, and reconnects retained data on re-import", async () => {
    const game = await importGame();
    const browserData = ownedPath(store.directory, "browser-data", game.id);
    await mkdir(browserData, { recursive: true });
    await writeFile(path.join(browserData, "save.json"), "save");
    await expect(importGame()).rejects.toThrow("already in your library");
    await library.handle({ action: "remove", id: game.id, deleteData: false });
    expect((await library.snapshot()).games).toHaveLength(0);
    const restored = await importGame();
    expect(restored.id).toBe(game.id);
    expect(await readFile(path.join(browserData, "save.json"), "utf8")).toBe("save");
    const reopened = new LibraryStore(store.directory);
    await reopened.load();
    expect(reopened.value.games[0]?.name).toBe("The Quiet Valley");
    expect(reopened.value.games[0]?.tags).toEqual(["adventure"]);
  });
  it("deletes browser data only when selected and never removes original saves or plugin backups", async () => {
    const game = await importGame();
    const browserData = ownedPath(store.directory, "browser-data", game.id);
    await mkdir(browserData, { recursive: true });
    await writeFile(path.join(browserData, "save.json"), "browser save");
    await writeFile(path.join(root, "save.json"), "original save");
    await changePlugins(store, game, digest(original), { index: 0, enabled: false });
    await library.handle({ action: "remove", id: game.id, deleteData: true });
    expect(await exists(browserData)).toBe(false);
    expect(await readFile(path.join(root, "save.json"), "utf8")).toBe("original save");
    expect(
      await exists(path.join(ownedPath(store.directory, "plugin-backups", game.id), "original.js")),
    ).toBe(true);
  });
  it("does not replace a corrupted library with an empty one", async () => {
    await importGame();
    await writeFile(store.file, "damaged data");
    await expect(new LibraryStore(store.directory).load()).rejects.toThrow("has not been replaced");
    expect(await readFile(store.file, "utf8")).toBe("damaged data");
  });
});

describe("plugin editing", () => {
  it("keeps the game locked until a plugin edit finishes", async () => {
    const game = await importGame();
    const editing = library.handle({
      action: "togglePlugin",
      id: game.id,
      hash: digest(original),
      index: 0,
      enabled: false,
    });
    await expect(
      library.handle({ action: "remove", id: game.id, deleteData: false }),
    ).rejects.toThrow("already in progress");
    await editing;
    expect((await listPlugins(store, game)).plugins[0]?.enabled).toBe(false);
    await library.handle({ action: "remove", id: game.id, deleteData: false });
    expect((await library.snapshot()).games).toHaveLength(0);
  });
  it("changes only the selected state, keeps the first backup, and restores exact original bytes after restart", async () => {
    const game = await importGame();
    let list = await changePlugins(store, game, digest(original), { index: 0, enabled: false });
    let source = await readFile(path.join(root, "js", "plugins.js"), "utf8");
    const entries = JSON.parse(source.slice(source.indexOf("["), source.lastIndexOf("]") + 1));
    expect(entries[0]).toMatchObject({
      name: "Lighting",
      status: false,
      parameters: { intensity: "2" },
      custom: "keep",
    });
    list = await changePlugins(store, game, list.hash, { index: 1, enabled: true });
    const reopened = new LibraryStore(store.directory);
    await reopened.load();
    await changePlugins(reopened, game, list.hash, "restore");
    source = await readFile(path.join(root, "js", "plugins.js"), "utf8");
    expect(source).toBe(original);
  });
  it("refuses stale toggles and refuses to restore over an external change", async () => {
    const game = await importGame();
    const list = await changePlugins(store, game, digest(original), { index: 0, enabled: false });
    await expect(
      changePlugins(store, game, digest(original), { index: 1, enabled: true }),
    ).rejects.toThrow("changed");
    const changed = original.replace("Lighting effects", "Updated by game patch");
    await writeFile(path.join(root, "js", "plugins.js"), changed);
    expect((await listPlugins(store, game)).conflict).toBe(true);
    await expect(changePlugins(store, game, digest(changed), "restore")).rejects.toThrow(
      "outside Aperto",
    );
    expect(await readFile(path.join(root, "js", "plugins.js"), "utf8")).toBe(changed);
    expect(list.canRestore).toBe(true);
  });
  it("reconciles a write interrupted between file replacement and state commit", async () => {
    const game = await importGame();
    const list = await changePlugins(store, game, digest(original), { index: 0, enabled: false });
    await store.update((state) => ({
      ...state,
      backups: state.backups.map((backup) => ({
        ...backup,
        lastWritten: backup.original,
        pending: list.hash,
      })),
    }));
    const reopened = new LibraryStore(store.directory);
    await reopened.load();
    await changePlugins(reopened, game, list.hash, "restore");
    expect(await readFile(path.join(root, "js", "plugins.js"), "utf8")).toBe(original);
  });
  it("does not execute custom plugin scripts or enable a missing plugin", async () => {
    expect(() =>
      parsePlugins('var $plugins = (() => { throw new Error("executed"); })();'),
    ).toThrow("custom plugin configuration");
    const game = await importGame();
    await rm(path.join(root, "js", "plugins", "Weather.js"));
    await expect(
      changePlugins(store, game, digest(original), { index: 1, enabled: true }),
    ).rejects.toThrow();
    expect(await readFile(path.join(root, "js", "plugins.js"), "utf8")).toBe(original);
  });
});

describe.runIf(process.platform === "darwin" && process.arch === "arm64")(
  "launch observation",
  () => {
    it("treats a short clean exit as a session and records abnormal exits without changing runtimes", async () => {
      const game = await importGame();
      const version = "0.100.0";
      const executable = runtimeExecutable(store.directory, version);
      await mkdir(path.dirname(executable), { recursive: true });
      await store.update((state) => ({
        ...state,
        runtimes: [{ version, installedAt: new Date().toISOString(), sha256: "fixture" }],
        games: state.games.map((entry) => ({ ...entry, runtime: version })),
      }));
      await writeFile(executable, "#!/bin/sh\nprintf '%s\\n' \"$@\"\nexit 0\n");
      await chmod(executable, 0o755);
      await library.handle({ action: "launch", id: game.id });
      await expect.poll(() => store.value.launches[0]?.outcome).toBe("ended");
      expect(store.value.launches[0]?.log).toContain("--user-data-dir=");
      expect(store.value.launches[0]?.log).toContain(game.root);
      await writeFile(executable, '#!/bin/sh\nprintf "failed fixture" >&2\nexit 2\n');
      await library.handle({ action: "launch", id: game.id });
      await expect.poll(() => store.value.launches[0]?.outcome).toBe("failed");
      expect(store.value.launches[0]?.detail).toContain("code 2");
      expect(store.value.games[0]?.runtime).toBe(version);
    });
  },
);
